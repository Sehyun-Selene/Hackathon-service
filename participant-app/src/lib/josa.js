// =====================================================================
//  조사 붙이기 — 앞 글자의 받침을 보고 고릅니다.
//
//  메뉴·재료 이름은 config 에서 오고 해커톤 준비 중에도 바뀝니다. 문장에
//  '이(가)' 처럼 둘 다 적어두면 어느 이름이 와도 어색하고, 하나만 박아두면
//  이름이 바뀌는 순간 틀립니다. 그때그때 붙입니다.
//
//    을를('아침')   → '아침을'      을를('피자')   → '피자를'
//    이가('밀')     → '밀이'        이가('우유')   → '우유가'
//
//  한글이 아닌 글자(영문·숫자·기호)로 끝나면 받침 없는 쪽으로 봅니다 —
//  'HOPE를' 처럼 읽는 게 'HOPE을' 보다 자연스럽습니다.
// =====================================================================
export const 받침 = (말) => {
  const 끝 = String(말 ?? '').trim().slice(-1).charCodeAt(0)
  if (!(끝 >= 0xac00 && 끝 <= 0xd7a3)) return false
  return (끝 - 0xac00) % 28 !== 0
}

export const 을를 = (말) => 말 + (받침(말) ? '을' : '를')
export const 이가 = (말) => 말 + (받침(말) ? '이' : '가')
